test_that("only the declared hosted example profile starts the deployment", {
    mode <- BreastSubtypeR:::.shiny_hosted_profile
    expect_false(mode("local"))
    expect_true(mode("example-only", deployment = TRUE))
    for (p in list(NULL, "", "local", NA_character_, "Example-only", c("local", "example-only")))
        expect_error(mode(p, deployment = TRUE))
    expect_error(mode("research-uploads", deployment = TRUE), "closed")
    withr::local_options(BreastSubtypeR.maxIterations = 101L)
    expect_error(BreastSubtypeR:::.shiny_iteration_limit())
})

test_that("hosted sessions reject file records, retain trusted examples and cap iterations", {
    withr::local_options(BreastSubtypeR.profile = "example-only",
                         BreastSubtypeR.maxIterations = 100L)
    app <- new.env(parent = asNamespace("shiny"))
    path <- system.file("ShinyBreastSubtypeR/server.R", package = "BreastSubtypeR")
    sys.source(path, app)
    marker <- "SYNTHETIC_PRIVACY_CANARY"
    fake <- data.frame(name = paste0(marker, ".csv"), size = 1,
                       datapath = file.path(tempdir(), marker))
    shiny::testServer(app$server, {
        expect_null(output$upload_GEX)
        expect_null(output$upload_clinic)
        expect_null(output$upload_anno)
        expect_false(grepl('type="file"', as.character(output$pam50_calibration$html), fixed = TRUE))
        session$setInputs(upload_started = "GEX", GEX = fake, clinic = fake, anno = fake, medians = fake)
        expect_null(reactive_files$source)
        expect_null(reference_file())
        expect_false(any(lengths(uploads()) > 0L))
        expect_false(grepl(marker, safe_detail(simpleError(marker)), fixed = TRUE))
        session$setInputs(map = 1)
        expect_false(mapping_current())
        session$setInputs(example_choice = "oslo", confirm_example = 1, BSmethod = "sspbc", k_subtypes = "5")
        session$setInputs(map = 2)
        expect_true(mapping_current())
        expect_false(raw_mode())
        session$setInputs(upload_started = "GEX_1", GEX_1 = fake)
        do.call(session$setInputs, setNames(list(fake), calibration_ns()("medians")))
        expect_null(reference_file())
        expect_identical(reactive_files$source, "example")
        expect_true(mapping_current())
        session$setInputs(BSmethod = "PAM50")
        do.call(session$setInputs, setNames(list("External", "Given.mdns"),
            c(calibration_ns()("calibration"), calibration_ns()("external"))))
        session$setInputs(run = 8)
        expect_null(current_prediction())
        expect_match(reactive_files$error, "Choose a built-in")
        session$setInputs(BSmethod = "cIHC.itr", iteration = 101, ratio = 54/64, run = 1)
        expect_null(current_prediction())
        expect_match(reactive_files$error, "up to 100")
        session$setInputs(example_choice = "tcga", confirm_example = 2)
        expect_true(raw_mode())
        expect_false(mapping_current())
        expect_null(current_prediction())
        expect_error(write_download(tempfile()), "No current prediction", fixed = TRUE)
    })
})
